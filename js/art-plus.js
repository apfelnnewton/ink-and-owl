/* Lupin: a pinned lunar calendar, the full moon ringed in red ink */
function moonPath(cx, cy, r, f, waxing){
  if (f <= 0.02 || f >= 0.98) return '';
  const rx = r1(r * Math.abs(1 - 2 * f));
  const top = `${r1(cx)} ${r1(cy - r)}`, bot = `${r1(cx)} ${r1(cy + r)}`;
  if (waxing) return `M${top} A${r} ${r} 0 0 1 ${bot} A${rx} ${r} 0 0 ${f < .5 ? 0 : 1} ${top} Z`;
  return `M${top} A${r} ${r} 0 0 0 ${bot} A${rx} ${r} 0 0 ${f < .5 ? 1 : 0} ${top} Z`;
}
function moonChart(){
  const x = 88, y = 154, w = 74, h = 46; let s = `<g transform="rotate(2.5 ${x + w / 2} ${y + h / 2})">`;
  s += `<rect x="${x + 1.5}" y="${y + 2.5}" width="${w}" height="${h}" fill="#000" opacity=".35"/><rect x="${x}" y="${y}" width="${w}" height="${h}" fill="#DCCDA6"/>`;
  s += `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="none" stroke="#8A7A55" stroke-width=".5"/>`;
  s += `<text x="${x + w / 2}" y="${y + 13}" text-anchor="middle" font-family="'IM Fell English', Georgia, serif" font-style="italic" font-size="8.5" fill="#2A2118">Phases of the Moon</text>`;
  const phases = [[0, 1], [.25, 1], [.5, 1], [.75, 1], [1, 1], [.75, 0], [.5, 0]];
  phases.forEach((p, k) => { const cx = x + 8 + k * 9.6, cy = y + 25, r = 3.6;
    s += `<circle cx="${r1(cx)}" cy="${cy}" r="${r}" fill="${p[0] >= 1 ? '#F3EBD2' : '#2A2118'}" stroke="#2A2118" stroke-width=".6"/>`;
    const lit = moonPath(cx, cy, r, p[0], p[1]); if (lit) s += `<path d="${lit}" fill="#F3EBD2"/>`;
    if (p[0] >= 1) s += `<ellipse cx="${r1(cx)}" cy="${cy}" rx="6.2" ry="5.6" fill="none" stroke="#9A1F1F" stroke-width="1" transform="rotate(-12 ${r1(cx)} ${cy})"/><path d="M${r1(cx - 4)} ${cy + 8} q4 2 8 -1" stroke="#9A1F1F" stroke-width=".8" fill="none"/>`;
  });
  s += `<path d="M${x + 7} ${y + 37} h30 M${x + 7} ${y + 41} h22 M${x + 44} ${y + 37} h22" stroke="#2A2118" stroke-width=".7" opacity=".55"/>`;
  s += pin(x + w / 2, y + 4) + '</g>';
  return s;
}

