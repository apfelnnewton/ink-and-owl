/* Dumbledore: a night-sky fanlight in the arch head, brass glazing bars radiating like the sun knocker's rays */
function fanlight(){
  const r = RL - 6, cy = SPRING, R = rng(907); let s = '';
  s += `<path d="M${CX - r} ${cy} A${r} ${r} 0 0 1 ${CX + r} ${cy} Z" fill="url(#g-night)"/>`;
  s += `<path d="M${CX - r} ${cy} A${r} ${r} 0 0 1 ${CX + r} ${cy} Z" fill="url(#g-nightglow)" class="glow"/>`;
  let n = 0;
  while (n < 26){
    const x = CX - r + R() * 2 * r, y = cy - R() * r;
    if ((x - CX) ** 2 + (y - cy) ** 2 > (r - 5) ** 2) continue;
    if ((x - CX) ** 2 + (y - 170) ** 2 < 26 ** 2) continue;
    if ((x - (CX + 40)) ** 2 + (y - 158) ** 2 < 12 ** 2) continue;
    if (n % 3 === 0) s += `<path class="tw" style="animation-delay:-${r1(R() * 4)}s;animation-duration:${r1(2.4 + R() * 2.6)}s" d="${star4(x, y, 1.8 + R() * 1.6)}" fill="#F7E7B0"/>`;
    else s += `<circle class="tw" style="animation-delay:-${r1(R() * 4)}s;animation-duration:${r1(3 + R() * 3)}s" cx="${r1(x)}" cy="${r1(y)}" r="${r1(.45 + R() * .6)}" fill="#fff" opacity=".85"/>`;
    n++;
  }
  const mx = CX + 40, my = 158;
  s += `<circle cx="${mx}" cy="${my}" r="12" fill="#F3E2A6" opacity=".12" class="glow"/>`;
  s += `<path d="M${mx} ${my - 6.5} A6.5 6.5 0 1 0 ${mx} ${my + 6.5} A4.6 6.5 0 1 1 ${mx} ${my - 6.5} Z" fill="#F3E2A6"/>`;
  for (let a = 15; a <= 165; a += 30){ const t = a * Math.PI / 180, ex = CX + r * Math.cos(t), ey = cy - r * Math.sin(t);
    s += `<path d="M${CX} ${cy} L${r1(ex)} ${r1(ey)}" stroke="#6A5218" stroke-width="2.8"/><path d="M${CX} ${cy} L${r1(ex)} ${r1(ey)}" stroke="#D9BC6A" stroke-width="1.1"/>`; }
  s += `<path d="M${CX - r} ${cy} A${r} ${r} 0 0 1 ${CX + r} ${cy}" fill="none" stroke="#6A5218" stroke-width="4"/><path d="M${CX - r} ${cy} A${r} ${r} 0 0 1 ${CX + r} ${cy}" fill="none" stroke="#D9BC6A" stroke-width="1.6"/>`;
  s += `<rect x="${CX - RL}" y="${cy - 1}" width="${2 * RL}" height="6" fill="url(#g-brass)" stroke="#6A5218" stroke-width=".8"/>`;
  return s;
}
