const esc = s => String(s).replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
function shadow(cx, cy, rx, ry, o = .45){ return `<ellipse cx="${r1(cx)}" cy="${r1(cy)}" rx="${rx}" ry="${ry}" fill="#000" opacity="${o}"/>`; }
function pin(x, y){ return `<circle cx="${r1(x)}" cy="${r1(y)}" r="2.6" fill="url(#g-brass)" stroke="#6A5218" stroke-width=".5"/><circle cx="${r1(x - .8)}" cy="${r1(y - .8)}" r=".8" fill="#fff" opacity=".6"/>`; }
