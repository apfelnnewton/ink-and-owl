/* ink tally marks in fives; each stroke draws in turn */
export function tally(n, seed){
  const R = rng(seed), gw = 36; let s = '';
  for (let i = 0; i < n; i++){
    const g = Math.floor(i / 5), k = i % 5, x0 = g * gw + 5;
    let d;
    if (k < 4){ const x = x0 + k * 6.4 + (R() - .5) * 1.4; d = `M${r1(x)} ${r1(3 + R() * 2)} Q${r1(x + (R() - .5) * 2.4)} 13 ${r1(x + (R() - .5) * 1.6)} ${r1(23 - R() * 2)}`; }
    else d = `M${r1(x0 - 4)} ${r1(18 + R() * 2)} Q${r1(x0 + 10)} ${r1(12 + R() * 2)} ${r1(x0 + 24)} ${r1(6 + R() * 2)}`;
    s += `<path class="ink" style="--i:${i}" pathLength="1" d="${d}" stroke="#2A2118" stroke-width="1.9" fill="none" stroke-linecap="round"/>`;
  }
  return {svg: s, width: Math.max(1, Math.ceil(n / 5)) * gw};
}

