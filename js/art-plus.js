/* each stone gets a pillowed face: catch-light on top, shadow gathering underneath */
export function shadeStones(svg){
  return svg
    .replace(/<rect x="([-\d.]+)" y="([-\d.]+)" width="([\d.]+)" height="([\d.]+)" rx="(3\.5|2\.5)" fill="#[0-9a-fA-F]{6}"\/>/g,
      (m, x, y, w, h, rx) => m + `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}" fill="url(#g-stone)"/>`)
    .replace(/<polygon points="([^"]+)" fill="#[0-9a-fA-F]{6}" stroke="#0C100E" stroke-width="2.4" stroke-linejoin="round"\/>/g,
      (m, p) => m + `<polygon points="${p}" fill="url(#g-stone)"/>`);
}

